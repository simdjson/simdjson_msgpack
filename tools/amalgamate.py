#!/usr/bin/env python3
"""Writes the library as one header and one source file:

    python3 tools/amalgamate.py [output directory, default singleheader]

gives simdjson_msgpack.h and simdjson_msgpack.cpp. Compile simdjson_msgpack.cpp with
simdjson's own single files (simdjson.h, simdjson.cpp) in the same directory.
"""
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# The source files, in order; their #include "..." of each other are removed.
SOURCES = [
    "third_party/zmij/zmij.h",
    "third_party/zmij/zmij.cc",
    "src/buffer.h",
    "src/parallel.h",
    "src/to_msgpack.cpp",
    "src/to_json.cpp",
    "src/c_api.cpp",
]
LOCAL = {os.path.basename(p) for p in SOURCES} | {"simdjson_msgpack.h"}
INCLUDE = re.compile(r'^\s*#\s*include\s+"([^"]+)"')


ZMIJ_WARNINGS_OFF = """#if defined(__clang__)
#pragma clang diagnostic push
#pragma clang diagnostic ignored "-Wunused-function"
#pragma clang diagnostic ignored "-Wunused-parameter"
#pragma clang diagnostic ignored "-Wunused-variable"
#pragma clang diagnostic ignored "-Wunneeded-internal-declaration"
#elif defined(__GNUC__)
#pragma GCC diagnostic push
#pragma GCC diagnostic ignored "-Wunused-function"
#pragma GCC diagnostic ignored "-Wunused-parameter"
#pragma GCC diagnostic ignored "-Wunused-variable"
#endif
"""
ZMIJ_WARNINGS_ON = """#if defined(__clang__)
#pragma clang diagnostic pop
#elif defined(__GNUC__)
#pragma GCC diagnostic pop
#endif
"""


def version():
    try:
        return subprocess.check_output(["git", "describe", "--tags", "--always", "--dirty"],
                                       cwd=ROOT, text=True, stderr=subprocess.DEVNULL).strip()
    except (OSError, subprocess.CalledProcessError):
        return "unknown"


def read(path):
    with open(os.path.join(ROOT, path), encoding="utf-8") as f:
        return f.read()


def body(path):
    lines = []
    for line in read(path).splitlines():
        m = INCLUDE.match(line)
        if m and os.path.basename(m.group(1)) in LOCAL:
            lines.append(f"// {line.strip()}: included above")
        elif line.strip() == "#pragma once":
            continue
        else:
            lines.append(line)
    return "\n".join(lines)


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "singleheader")
    os.makedirs(out, exist_ok=True)
    banner = (f"/* simdjson_msgpack {version()}: https://github.com/simdjson/simdjson_msgpack\n"
              " * Apache License 2.0. Generated by tools/amalgamate.py: do not edit. */\n")
    with open(os.path.join(out, "simdjson_msgpack.h"), "w", encoding="utf-8", newline="\n") as f:
        f.write(banner + read("include/simdjson_msgpack.h"))
    parts = [banner, '#include "simdjson_msgpack.h"\n']
    for path in SOURCES:
        text = f"/* begin file {path} */\n{body(path)}\n/* end file {path} */\n"
        if path.startswith("third_party/zmij/"):  # unused code, on some targets
            # With SIMDJSON_MSGPACK_EXTERNAL_ZMIJ, zmij comes from elsewhere
            # (zmij.h on the include path, zmij.cc compiled on its own).
            if path.endswith(".h"):
                text = ("#ifdef SIMDJSON_MSGPACK_EXTERNAL_ZMIJ\n#include \"zmij.h\"\n#else\n"
                        + ZMIJ_WARNINGS_OFF + text + ZMIJ_WARNINGS_ON + "#endif\n")
            else:
                text = ("#ifndef SIMDJSON_MSGPACK_EXTERNAL_ZMIJ\n" + ZMIJ_WARNINGS_OFF + text
                        + ZMIJ_WARNINGS_ON + "#endif\n")
        parts.append(text)
        if path == "third_party/zmij/zmij.h":
            parts.insert(-1, "/* zmij: https://github.com/vitaut/zmij, MIT license:\n"
                         + read("third_party/zmij/LICENSE").rstrip() + "\n*/\n")
    with open(os.path.join(out, "simdjson_msgpack.cpp"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(parts))


if __name__ == "__main__":
    main()
